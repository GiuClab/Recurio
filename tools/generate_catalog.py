"""Generate Kotlin data from reviewed catalog metadata. Run from repository root."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
entries = json.loads((root / 'catalog/services.json').read_text())
assert len({e['id'] for e in entries}) == len(entries)
assert len({e['name'] for e in entries}) == len(entries)
quote = lambda s: json.dumps(s, ensure_ascii=False)
lines = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Generated by tools/generate_catalog.py; edit catalog/services.json.', 'package io.github.giuclab.recurio', '', 'val catalogEntries = listOf(']
for e in entries:
    rules = ', '.join(map(quote, e['rules']))
    aliases = ", ".join(map(quote, e["aliases"]))
    lines.append(f' Service({quote(e["name"])}, listOf({rules}), {quote(e["category"])}, {quote(e["id"])}, listOf({aliases})),')
lines.append(')')
(root/'app/src/main/java/io/github/giuclab/recurio/CatalogEntries.kt').write_text('\n'.join(lines)+'\n')
print(f'{len(entries)} catalog entries generated')
